std::string hash(const fs::path &path) {
    std::ifstream input(path, std::ios::binary);
    if (!input) {
        return {};
    }
    lightning::packages::Sha256 value;
    std::array<std::uint8_t, 65536> bytes{};
    while (input) {
        input.read(reinterpret_cast<char *>(bytes.data()), bytes.size());
        value.update(bytes.data(), static_cast<std::size_t>(input.gcount()));
    }
    return input.eof() ? value.finish() : std::string{};
}
bool copy_payload(const fs::path &from, const fs::path &to) {
    std::error_code error;
    if (!fs::is_regular_file(from, error) || fs::is_symlink(from, error)) {
        return false;
    }
    fs::create_directories(to.parent_path(), error);
    return !error && fs::copy_file(from, to, fs::copy_options::none, error) && !error &&
           hash(from) == hash(to);
}
std::string quote(const std::string &text) {
    std::string result = "\"";
    for (auto byte : text) {
        if (byte == '\\' || byte == '"') {
            result += '\\';
        }
        result += byte;
    }
    return result + '"';
}
std::string identity(const xhci::PciIdentity &id) {
    char bytes[96]{};
    std::snprintf(bytes, sizeof(bytes), "PCI\\VEN_%04X&DEV_%04X&SUBSYS_%04X%04X&REV_%02X",
                  id.vendor, id.device, id.subsystem_device, id.subsystem_vendor, id.revision);
    return bytes;
}
bool write(const fs::path &path, const std::string &text) {
    std::ofstream output(path, std::ios::binary);
    output << text;
    output.close();
    return static_cast<bool>(output);
}
std::string header() {
    return "; Generated by xhci_package_provider from central board profiles.\r\n"
           "[Version]\r\nSignature=\"$Windows NT$\"\r\nClass=USB\r\n"
           "ClassGUID={36FC9E60-C465-11CF-8056-444553540000}\r\n"
           "Provider=%Provider%\r\nDriverVer=10/25/2026,0.1.0.0\r\n\r\n"
           "[DestinationDirs]\r\nPayload=12\r\n\r\n"
           "[SourceDisksNames]\r\n1=%Disk%,,,\r\n\r\n[SourceDisksFiles]\r\n";
}
std::string inf(const std::string &binary, const std::string &service,
                const std::vector<std::string> &ids, const std::vector<std::string> &names,
                unsigned start, bool preinstalled = false) {
    std::string text = header() + binary +
                       "=1\r\n\r\n[Manufacturer]\r\n"
                       "%Provider%=Models,NTx86\r\n\r\n[Models.NTx86]\r\n";
    for (std::size_t i = 0; i < ids.size(); ++i) {
        text += "%Device" + std::to_string(i) + "%=Install," + ids[i] + "\r\n";
    }
    text += "\r\n[Install.NT]\r\n" + std::string(preinstalled ? "" : "CopyFiles=Payload\r\n") +
            "\r\n[Payload]\r\n" + binary +
            "\r\n\r\n[Install.NT.Services]\r\nAddService=" + service +
            ",0x00000002,Service\r\n\r\n[Service]\r\nServiceType=1\r\nStartType=" +
            std::to_string(start) + "\r\nErrorControl=1\r\nServiceBinary=%12%\\" + binary +
            "\r\nLoadOrderGroup=" + std::string(start == 0 ? "Boot Bus Extender" : "Base") +
            "\r\n\r\n[Strings]\r\n"
            "Provider=\"XHCI-ReactOS\"\r\nDisk=\"XHCI-ReactOS driver package\"\r\n";
    for (std::size_t i = 0; i < names.size(); ++i) {
        text += "Device" + std::to_string(i) + "=\"" + names[i] + "\"\r\n";
    }
    return text;
}
struct Payload {
    std::string source, destination, previous, service;
    bool reboot{};
    std::string installed_baseline{};
};
std::string payload(const fs::path &root, const Payload &file) {
    return "{\"source\":" + quote(file.source) + ",\"sha256\":" + quote(hash(root / file.source)) +
           ",\"destination\":" + quote(file.destination) + ",\"previous_sha256\":[" +
           (file.previous.empty() ? "" : quote(file.previous)) +
           (file.installed_baseline.empty() || file.installed_baseline == file.previous
                ? ""
                : "," + quote(file.installed_baseline)) +
           "],\"reboot\":" + (file.reboot ? "true" : "false") +
           ",\"boot_service\":" + quote(file.service) + "}";
}
std::string package(const fs::path &root, const std::string &id, const std::string &license,
                    const std::vector<Payload> &files, const std::vector<std::string> &dependencies,
                    const std::string &driver_inf, const std::vector<std::string> &ids) {
    std::string text =
        "{\"id\":" + quote(id) + ",\"label\":" + quote("XHCI-ReactOS " + id) +
        ",\"version\":\"20261025\",\"os\":\"reactos\",\"arch\":\"i386\",\"requires\":[";
    for (std::size_t i = 0; i < dependencies.size(); ++i) {
        text += (i ? "," : "") + quote(dependencies[i]);
    }
    text += "],\"required_versions\":{";
    for (std::size_t i = 0; i < dependencies.size(); ++i) {
        text += (i ? "," : "") + quote(dependencies[i]) + ":\"20261025\"";
    }
    text += "},\"license\":" + payload(root, {license, {}, {}, {}, false}) + ",\"files\":[";
    for (std::size_t i = 0; i < files.size(); ++i) {
        text += (i ? "," : "") + payload(root, files[i]);
    }
    text += "],\"drivers\":[";
    if (!driver_inf.empty()) {
        text += "{\"inf\":" + quote(driver_inf) + ",\"hardware_ids\":[";
        for (std::size_t i = 0; i < ids.size(); ++i) {
            text += (i ? "," : "") + quote(ids[i]);
        }
        text += "]}";
    }
    return text + "]}";
}
std::string qword(std::uint64_t value) {
    std::ostringstream text;
    text << std::hex << std::setfill('0');
    for (unsigned i = 0; i < 8; ++i) {
        text << (i ? "," : "") << std::setw(2) << ((value >> (i * 8)) & 0xff);
    }
    return text.str();
}
bool boot_metadata(const fs::path &root, std::uint32_t signature, std::uint32_t sectors) {
    std::error_code error;
    if (fs::exists(root, error) || error || !fs::create_directories(root, error) || error) {
        return false;
    }
    const std::string system = "SYSTEM\\CurrentControlSet\\";
    std::ostringstream text;
    text << "; Generated native USB boot policy; apply to a copied complete installed SYSTEM.\n"
            "[Version]\nSignature=\"$Windows NT$\"\n\n[AddReg]\n";
    for (const auto &service : {std::string("xhci"), std::string("XhciBoot")}) {
        const auto key = system + "Services\\" + service;
        text << "HKLM,\"" << key << "\",\"Type\",0x00010001,1\n"
             << "HKLM,\"" << key << "\",\"Start\",0x00010001,0\n"
             << "HKLM,\"" << key << "\",\"ErrorControl\",0x00010001,3\n"
             << "HKLM,\"" << key << "\",\"Group\",0,\"Boot Bus Extender\"\n"
             << "HKLM,\"" << key << "\",\"ImagePath\",0x00020000,\"system32\\drivers\\"
             << (service == "XhciBoot" ? "xhciboot.sys" : "xhci.sys") << "\"\n";
    }
    const auto key = system + "Services\\XhciBoot";
    text << "HKLM,\"" << key << "\",\"MbrSignature\",0x00010001,0x" << std::hex << signature << "\n"
         << "HKLM,\"" << key << "\",\"PartitionNumber\",0x00010001,1\n"
         << "HKLM,\"" << key << "\",\"PartitionOffset\",0x000b0001," << qword(1048576) << "\n"
         << "HKLM,\"" << key << "\",\"PartitionLength\",0x000b0001,"
         << qword(std::uint64_t(sectors) * 512) << "\n";
    for (const auto &service :
         {"usbhub", "usbstor", "disk", "fastfat", "hidusb", "kbdhid", "mouhid"}) {
        text << "HKLM,\"" << system << "Services\\" << service << "\",\"Start\",0x00010001,0\n";
    }
    for (std::size_t i = 0; i < xhci::board_controller_count(); ++i) {
        auto id = identity(xhci::board_controller_at(i)->identity);
        std::replace(id.begin(), id.end(), '\\', '#');
        text << "HKLM,\"" << system << "Control\\CriticalDeviceDatabase\\" << id
             << "\",\"Service\",0,\"xhci\"\n"
             << "HKLM,\"" << system << "Control\\CriticalDeviceDatabase\\" << id
             << "\",\"ClassGUID\",0,\"{36FC9E60-C465-11CF-8056-444553540000}\"\n";
    }
    text << "HKLM,\"" << system
         << "Control\\CriticalDeviceDatabase\\USB#ROOT_HUB30\",\"Service\",0,\"usbhub\"\n"
         << "HKLM,\"" << system
         << "Control\\CriticalDeviceDatabase\\USB#ROOT_HUB30\",\"ClassGUID\",0,\"{36FC9E60-C465-"
            "11CF-8056-444553540000}\"\n"
         << "HKLM,\"SYSTEM\\Setup\",\"SetupType\",0x00010001,0\n"
         << "HKLM,\"SYSTEM\\Setup\",\"SystemSetupInProgress\",0x00010001,0\n"
         << "HKLM,\"SYSTEM\\Setup\",\"CmdLine\",0,\"\"\n"
         << "HKLM,\"" << system
         << "Control\\Session Manager\\Memory Management\",\"PagingFiles\",0x00010000,\"\"\n";
    const std::string loader =
        "[FREELOADER]\r\nTimeOut=10\r\nDefaultOS=PersistentUSB\r\n\r\n"
        "[Display]\r\nTitleText=ReactOS persistent USB\r\nMinimalUI=Yes\r\n\r\n"
        "[Operating Systems]\r\nPersistentUSB=\"ReactOS persistent USB\"\r\n"
        "PersistentUSB_Debug=\"ReactOS persistent USB (serial diagnostics)\"\r\n\r\n"
        "[PersistentUSB]\r\nBootType=Windows2003\r\nSystemPath=\\ReactOS\r\nOptions=/"
        "FASTDETECT\r\n\r\n"
        "[PersistentUSB_Debug]\r\nBootType=Windows2003\r\nSystemPath=\\ReactOS\r\n"
        "Options=/DEBUG /DEBUGPORT=COM1 /BAUDRATE=115200 /SOS\r\n";
    return write(root / "boot.inf", text.str()) && write(root / "freeldr.ini", loader) &&
           write(root / "RECOVERY.txt",
                 "Persistent USB image: legacy BIOS/CSM, MBR, FAT32, i386. UEFI-only boot is not "
                 "provided.\r\n"
                 "No disk installer runs at startup. Settings and installed drivers live on the "
                 "USB FAT32 volume.\r\n"
                 "Keep the original image and its hash before flashing a disposable USB device.\r\n"
                 "Use a separately booted recovery OS to copy files/registry backups from "
                 "XHCI-Recovery.\r\n"
                 "Do not remove/update the active boot controller in the running system. Build a "
                 "new image from a stopped copy.\r\n"
                 "A missing/ambiguous USB boot disk stops with INACCESSIBLE_BOOT_DEVICE; it never "
                 "selects an internal disk.\r\n"
                 "The source score does not establish physical or persistent-boot "
                 "qualification.\r\n");
}
