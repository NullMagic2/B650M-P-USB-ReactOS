int main(int argc, char **argv) {
    if (argc == 3 && std::string(argv[1]) == "--boot-infs") {
        const fs::path directory = argv[2];
        std::error_code error;
        if (fs::exists(directory, error) || error || !fs::create_directories(directory, error) ||
            error) {
            return 1;
        }
        std::vector<std::string> ids, names;
        for (std::size_t i = 0; i < xhci::board_controller_count(); ++i) {
            const auto *profile = xhci::board_controller_at(i);
            ids.push_back(identity(profile->identity));
            names.emplace_back(profile->name);
        }
        return write(directory / "xhci-boot.inf", inf("xhci.sys", "xhci", ids, names, 0, true)) &&
                       write(directory / "xhci-roots.inf",
                             inf("usbhub.sys", "usbhub", {"USB\\ROOT_HUB20", "USB\\ROOT_HUB30"},
                                 {"xHCI USB 2 Root Hub", "xHCI USB 3 Root Hub"}, 0, true))
                   ? 0
                   : 1;
    }
    if (argc == 5 && std::string(argv[1]) == "--boot-metadata") {
        char *end{};
        const auto signature = std::strtoul(argv[3], &end, 16);
        if (!end || *end || !signature || signature > UINT32_MAX) {
            return 2;
        }
        const auto sectors = std::strtoul(argv[4], &end, 10);
        return end && !*end && sectors >= 1024 * 1024 && sectors <= 16 * 1024 * 1024 &&
                       boot_metadata(argv[2], static_cast<std::uint32_t>(signature),
                                     static_cast<std::uint32_t>(sectors))
                   ? 0
                   : 1;
    }
    if (argc != 9 && argc != 10) {
        std::fprintf(
            stderr,
            "usage: xhci_package_provider OUTPUT CONTROLLER COMPAT SDK_BUILD PROJECT "
            "SOURCE_ARCHIVE SHARED_ENGINE INSTALLED_REACTOS_TREE [APPROVED_PREVIOUS_HCD_SHA256]\n");
        return 2;
    }
    const fs::path root = argv[1], controller = argv[2], compat = argv[3], sdk = argv[4],
                   project = argv[5], source_archive = argv[6], shared = argv[7],
                   baseline = argv[8];
    const auto previous_controller = argc == 10 ? std::string(argv[9]) : hash(controller);
    if (previous_controller.size() != 64 ||
        !std::all_of(previous_controller.begin(), previous_controller.end(),
                     [](char c) { return (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f'); })) {
        return 2;
    }
    std::error_code error;
    if (fs::exists(root, error) || error || !fs::create_directories(root, error) || error) {
        std::fprintf(stderr, "Output must be a new directory; existing packages are preserved.\n");
        return 1;
    }
    bool ok =
        copy_payload(controller, root / "xhci/xhci.sys") &&
        copy_payload(project / "packaging/INSTALL.txt", root / "INSTALL.txt") &&
        copy_payload(project / "LICENSE", root / "notices/GPL-2.0.txt") &&
        copy_payload(project / "compat/reactos/disk/license.txt", root / "notices/MS-PL.txt") &&
        copy_payload(shared / "notices/mingw-w64-copyright.txt", root / "notices/MinGW.txt") &&
        copy_payload(shared / "notices/gcc-runtime-copyright.txt", root / "notices/GCC.txt") &&
        copy_payload(source_archive, root / "source/complete-source.tar.gz");
    std::vector<std::string> board_ids, board_names;
    for (std::size_t i = 0; i < xhci::board_controller_count(); ++i) {
        const auto *profile = xhci::board_controller_at(i);
        board_ids.push_back(identity(profile->identity));
        board_names.emplace_back(profile->name);
    }
    const std::vector<std::string> root_ids{"USB\\ROOT_HUB20", "USB\\ROOT_HUB30"};
    ok = ok && write(root / "xhci/xhci.inf", inf("xhci.sys", "xhci", board_ids, board_names, 3));
    ok = ok && copy_payload(compat / "usbhub-xhci-i386.sys", root / "usbhub/usbhub.sys") &&
         copy_payload(compat / "usbstor-xhci-i386.sys", root / "usbstor/usbstor.sys") &&
         copy_payload(compat / "disk-xhci-i386.sys", root / "disk/disk.sys") &&
         copy_payload(compat / "hidusb-xhci-i386.sys", root / "hidusb/hidusb.sys") &&
         write(root / "usbhub/usbhub.inf", inf("usbhub.sys", "usbhub", root_ids,
                                               {"xHCI USB 2 Root Hub", "xHCI USB 3 Root Hub"}, 0));
    std::string catalog = "{\"schema\":1,\"packages\":[";
    for (const auto &module : {std::string("usbhub"), std::string("usbstor"), std::string("disk"),
                               std::string("hidusb")}) {
        const auto upstream = sdk /
                              (module == "disk"     ? "drivers/storage/class"
                               : module == "hidusb" ? "drivers/hid"
                                                    : "drivers/usb") /
                              module / (module + ".sys");
        const auto previous = hash(upstream);
        const auto baseline_hash = hash(baseline / "system32/drivers" / (module + ".sys"));
        ok = ok && previous.size() == 64 && baseline_hash.size() == 64;
        std::vector<Payload> files{{module + "/" + module + ".sys",
                                    "system32/drivers/" + module + ".sys", previous,
                                    module == "hidusb" ? "" : module, true, baseline_hash}};
        if (module == "usbhub") {
            files.push_back({"usbhub/usbhub.inf", {}, {}, {}, false});
        }
        catalog += package(root, "reactos-xhci-" + module,
                           module == "disk" ? "notices/MS-PL.txt" : "notices/GPL-2.0.txt", files,
                           {}, module == "usbhub" ? "usbhub/usbhub.inf" : "",
                           module == "usbhub" ? root_ids : std::vector<std::string>{}) +
                   ",";
    }
    catalog +=
        package(root, "xhci", "notices/GPL-2.0.txt",
                {{"xhci/xhci.sys", "system32/drivers/xhci.sys", previous_controller, {}, true},
                 {"xhci/xhci.inf", {}, {}, {}, false},
                 {"INSTALL.txt", {}, {}, {}, false},
                 {"notices/MS-PL.txt", {}, {}, {}, false},
                 {"notices/MinGW.txt", {}, {}, {}, false},
                 {"notices/GCC.txt", {}, {}, {}, false}},
                {"reactos-xhci-usbhub", "reactos-xhci-usbstor", "reactos-xhci-disk",
                 "reactos-xhci-hidusb"},
                "xhci/xhci.inf", board_ids) +
        "]}\n";
    ok = ok && write(root / "catalog.json", catalog);
    if (!ok) {
        std::fprintf(stderr,
                     "Incomplete provider inputs; partial new output retained for diagnosis.\n");
        return 1;
    }
    std::printf(
        "Provider staged: 5 exact PCI profiles, 2 logical roots, 4 real compatibility modules.\n");
    return 0;
}
